let lang = localStorage.getItem('lang') || 'ko';
function t(key) { return (I18N[lang] && I18N[lang][key]) || (I18N.ko[key]) || key; }
function setLang(l) {
  lang = l; localStorage.setItem('lang', l); document.documentElement.lang = l;
  applyI18n();
  document.querySelectorAll('#langSelect button').forEach((b) => b.classList.toggle('active', b.dataset.lang === l));
}
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  const nb = document.getElementById('noticeBody'); if (nb) nb.innerHTML = t('notice_body');
  if (window.onLangChanged) window.onLangChanged();
}
